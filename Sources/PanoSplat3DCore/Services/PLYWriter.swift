import Foundation

/// Writes binary little-endian `.ply` point clouds (`x, y, z, red, green, blue`) compatible with Brush, COLMAP, SuperSplat, and Unreal Engine.
public enum PLYWriter {
    public static func write(points: [ColoredPoint3D], to url: URL) throws {
        let header = """
        ply
        format binary_little_endian 1.0
        comment Generated by PanoSplat3D (COLMAP RDF: +X Right, +Y Down, +Z Forward)
        element vertex \(points.count)
        property float x
        property float y
        property float z
        property uchar red
        property uchar green
        property uchar blue
        end_header

        """

        let headerData = Data(header.utf8)
        let vertexStride = 15 // 3 * Float32 (12 bytes) + 3 * UInt8 (3 bytes)
        var payload = Data(capacity: headerData.count + points.count * vertexStride)
        payload.append(headerData)

        var vertexBytes = [UInt8](repeating: 0, count: points.count * vertexStride)
        vertexBytes.withUnsafeMutableBytes { rawBuffer in
            guard let base = rawBuffer.baseAddress else { return }
            for (index, pt) in points.enumerated() {
                let offset = index * vertexStride
                var xBits = pt.position.x.bitPattern.littleEndian
                var yBits = pt.position.y.bitPattern.littleEndian
                var zBits = pt.position.z.bitPattern.littleEndian

                memcpy(base.advanced(by: offset), &xBits, 4)
                memcpy(base.advanced(by: offset + 4), &yBits, 4)
                memcpy(base.advanced(by: offset + 8), &zBits, 4)
                base.storeBytes(of: pt.r, toByteOffset: offset + 12, as: UInt8.self)
                base.storeBytes(of: pt.g, toByteOffset: offset + 13, as: UInt8.self)
                base.storeBytes(of: pt.b, toByteOffset: offset + 14, as: UInt8.self)
            }
        }
        payload.append(contentsOf: vertexBytes)

        let directory = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try payload.write(to: url, options: .atomic)
    }
}
